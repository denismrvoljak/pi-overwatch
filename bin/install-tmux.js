// Installs the Overwatch tmux status row.
// Idempotent: re-running regenerates overwatch.conf and leaves the single
// marked `source-file` block in your tmux config alone.

import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { fileURLToPath } from "node:url";

const BLOCK_START = "# >>> pi-overwatch >>>";
const BLOCK_END = "# <<< pi-overwatch <<<";
const GENERATED_HEADER = "# Generated by `pi-overwatch install-tmux`. Re-running it overwrites this file.";

const exampleFile = fileURLToPath(new URL("../examples/tmux.conf", import.meta.url));
const cliFile = fileURLToPath(new URL("./pi-overwatch.js", import.meta.url));

function configHome() {
  return process.env.XDG_CONFIG_HOME || path.join(os.homedir(), ".config");
}

// tmux reads ~/.tmux.conf first, then the XDG location; follow whichever exists.
function tmuxConfPath() {
  const legacy = path.join(os.homedir(), ".tmux.conf");
  const xdg = path.join(configHome(), "tmux", "tmux.conf");
  if (fs.existsSync(legacy)) return legacy;
  if (fs.existsSync(xdg)) return xdg;
  return legacy;
}

function shellQuote(value) {
  return `'${String(value).replace(/'/g, `'\\''`)}'`;
}

// The PATH entry (e.g. /opt/homebrew/bin/node) survives upgrades; execPath
// often points into a versioned Cellar directory that does not.
function findNode() {
  for (const dir of (process.env.PATH || "").split(path.delimiter)) {
    const candidate = path.join(dir, "node");
    try {
      fs.accessSync(candidate, fs.constants.X_OK);
      return candidate;
    } catch {
      // keep looking
    }
  }
  return process.execPath;
}

// tmux's #() and key bindings run without your shell profile, so nvm/npm
// global bins are often missing from PATH. Pin node and the script instead.
function defaultCommand() {
  return `${shellQuote(findNode())} ${shellQuote(fs.realpathSync(cliFile))}`;
}

export function renderOverwatchConf(command) {
  const body = fs
    .readFileSync(exampleFile, "utf8")
    .replace(/^# Overwatch status row — requires pi-overwatch on tmux's PATH\.\n/, "")
    .replace(/#\(pi-overwatch /g, `#(${command} `)
    .replace(/"pi-overwatch"/g, `"${command}"`);
  return `${GENERATED_HEADER}\n${body}`;
}

function sourceBlock(overwatchConf) {
  const display = overwatchConf.replace(`${os.homedir()}/`, "~/");
  return `${BLOCK_START}\nsource-file ${display}\n${BLOCK_END}\n`;
}

function stripBlock(text) {
  const pattern = new RegExp(`\\n*${BLOCK_START}\\n[\\s\\S]*?${BLOCK_END}\\n?`, "g");
  return text.replace(pattern, "\n").replace(/\n{2,}$/, "\n");
}

// Lines outside our block that would fight the Overwatch row.
function conflictingLines(text) {
  return stripBlock(text)
    .split("\n")
    .filter((line) => !line.trim().startsWith("#"))
    .filter((line) => /status-format\[1\]|\bset(-option)?\s+(-\w+\s+)*status\s+[2-5]\b/.test(line));
}

function tmuxRunning() {
  try {
    execFileSync("tmux", ["list-sessions"], { stdio: "ignore", timeout: 1500 });
    return true;
  } catch {
    return false;
  }
}

function parseArgs(args) {
  const options = { dryRun: false, remove: false, reload: true, command: undefined };
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--dry-run") options.dryRun = true;
    else if (args[i] === "--uninstall") options.remove = true;
    else if (args[i] === "--no-reload") options.reload = false;
    else if (args[i] === "--command") options.command = args[++i];
  }
  return options;
}

export function installTmux(args = []) {
  const options = parseArgs(args);
  const confPath = tmuxConfPath();
  const overwatchConf = path.join(configHome(), "tmux", "overwatch.conf");
  const current = fs.existsSync(confPath) ? fs.readFileSync(confPath, "utf8") : "";
  const hasBlock = current.includes(BLOCK_START);

  if (options.remove) {
    const next = stripBlock(current);
    if (options.dryRun) {
      process.stdout.write(next);
      return;
    }
    if (hasBlock) {
      fs.copyFileSync(confPath, `${confPath}.overwatch-backup`);
      fs.writeFileSync(confPath, next, "utf8");
    }
    if (fs.existsSync(overwatchConf) && fs.readFileSync(overwatchConf, "utf8").startsWith(GENERATED_HEADER)) {
      fs.rmSync(overwatchConf);
    }
    process.stdout.write(`Removed the Overwatch row from ${confPath}\n`);
    process.stdout.write("Reload tmux (or restart the server) to drop the row from running clients.\n");
    return;
  }

  const rendered = renderOverwatchConf(options.command || defaultCommand());
  const next = hasBlock ? current : `${current}${current && !current.endsWith("\n") ? "\n" : ""}${current ? "\n" : ""}${sourceBlock(overwatchConf)}`;

  if (options.dryRun) {
    process.stdout.write(`--- ${overwatchConf}\n${rendered}\n--- ${confPath}\n${next}`);
    return;
  }

  fs.mkdirSync(path.dirname(overwatchConf), { recursive: true });
  fs.writeFileSync(overwatchConf, rendered, "utf8");
  if (!hasBlock) {
    if (current) fs.copyFileSync(confPath, `${confPath}.overwatch-backup`);
    fs.mkdirSync(path.dirname(confPath), { recursive: true });
    fs.writeFileSync(confPath, next, "utf8");
  }

  process.stdout.write(`Wrote ${overwatchConf}\n`);
  process.stdout.write(hasBlock ? `${confPath} already sources it\n` : `Added a source-file block to the end of ${confPath}\n`);

  const conflicts = conflictingLines(current);
  if (conflicts.length > 0) {
    process.stdout.write("Warning: these lines also configure extra status rows and may conflict:\n");
    for (const line of conflicts) process.stdout.write(`  ${line.trim()}\n`);
  }

  if (options.reload && tmuxRunning()) {
    try {
      execFileSync("tmux", ["source-file", overwatchConf], { stdio: "ignore", timeout: 3000 });
      process.stdout.write("Loaded into the running tmux server.\n");
    } catch {
      process.stdout.write(`Could not reload tmux; run: tmux source-file ${overwatchConf}\n`);
    }
  }
}
